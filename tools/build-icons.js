// Bundles the SVG icon kit and every icon group into assets/icons.js (loaded by icons.html and the game).
// Run with `node tools/build-icons.js` after editing anything under assets/.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const dir = path.join(root, 'assets/icons');
const order = (f) => (f === 'reference.js' ? '' : f); // reference first, then alphabetical
const files = ['assets/kit.js', 'assets/ui-icons.js',
  ...fs.readdirSync(dir).filter((f) => f.endsWith('.js')).sort((a, b) => order(a).localeCompare(order(b))).map((f) => 'assets/icons/' + f)];
const out = '// Generated by tools/build-icons.js from assets/kit.js, assets/ui-icons.js and assets/icons/*.js. Do not edit.\n' +
  files.map((f) => `// ---- ${f}\n${fs.readFileSync(path.join(root, f), 'utf8').trim()}\n`).join('\n');
fs.writeFileSync(path.join(root, 'assets/icons.js'), out);
console.log(`Wrote assets/icons.js (${files.length} files, ${Math.round(out.length / 1024)} KB)`);
